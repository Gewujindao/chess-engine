int evaluate(const Position& pos) {
    int score = 0;  // from White's point of view
    for (int type = PAWN; type <= KING; ++type) {
        Bitboard white = pos.pieces(WHITE, PieceType(type));
        while (white) {
            Square s = bb::pop_lsb(white);
            score += PIECE_VALUE[type] + PST[type][(7 - rank_of(s)) * 8 + file_of(s)];
        }
        Bitboard black = pos.pieces(BLACK, PieceType(type));
        while (black) {
            Square s = bb::pop_lsb(black);  // mirror vertically for Black
            score -= PIECE_VALUE[type] + PST[type][rank_of(s) * 8 + file_of(s)];
        }
    }
    return pos.side_to_move() == WHITE ? score : -score;
}
